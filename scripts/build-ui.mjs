/**
 * Generates the settings pages (ui/*.html), one per action, from a single template.
 * Run with: npm run ui
 *
 * Every page has the same "shared" section (server, API key, default player, priority users),
 * plus a few fields of its own. Writing them out by hand would mean six copies to keep in step.
 *
 * In Elgato's components, a field with `global` is saved once for the whole plugin; without it,
 * it's saved for that one key or dial.
 */
import { mkdirSync, writeFileSync } from "node:fs";

const OUT = "com.jere.jellyfin-remote.sdPlugin/ui";

const REMOTE_BUTTONS = [
	["playpause", "Play / pause"], ["stop", "Stop"], ["resume", "Resume (continue watching)"], ["next", "Next"], ["previous", "Previous"],
	["back10", "Back 10 seconds"], ["forward30", "Forward 30 seconds"],
	["subtitles", "Next subtitles"], ["audio", "Next audio track"], ["mute", "Mute"],
	["up", "Up"], ["down", "Down"], ["left", "Left"], ["right", "Right"], ["select", "OK / select"],
	["back", "Back"], ["home", "Home"], ["menu", "Menu"], ["info", "Info (on-screen display)"], ["fullscreen", "Fullscreen"],
];

const PAGES = {
	volume: {
		title: "Volume",
		fields: `<sdpi-item label="Step"><sdpi-range setting="step" min="1" max="10" step="1" default="5" showlabels></sdpi-range></sdpi-item>`,
		help: "Turn for volume, press to play or pause, tap the strip to mute.",
	},
	scrub: {
		title: "Seek",
		fields: `<sdpi-item label="Per click"><sdpi-select setting="step" default="10">
				<option value="5">5 seconds</option><option value="10">10 seconds</option>
				<option value="30">30 seconds</option><option value="60">1 minute</option>
			</sdpi-select></sdpi-item>`,
		help: "Turn to seek. Press to play or pause. Tap the left half of the strip to go back 10 seconds, the right half to go forward 30. Hold the strip to stop.",
	},
	tracks: {
		title: "Subtitles & audio",
		fields: "",
		help: "Turn through the subtitles (Off is one of them). Press, or hold the strip, for the next audio track. Tap the strip to turn subtitles off, and tap again to bring them back.",
	},
	navigate: {
		title: "Navigate menus",
		fields: `<sdpi-item label="Turning moves"><sdpi-select setting="axis" default="horizontal">
				<option value="horizontal">Left / right (hold and turn: up / down)</option>
				<option value="vertical">Up / down (hold and turn: left / right)</option>
			</sdpi-select></sdpi-item>`,
		help: "Turn to move left and right. Hold the dial down while turning to move up and down. Click (press and let go) for OK. Tap the strip for back, hold the strip for home.",
	},
	library: {
		title: "Continue watching",
		fields: `<sdpi-item label="Starts on"><sdpi-select setting="list" default="resume">
				<option value="resume">Continue watching</option><option value="nextup">Next up</option>
			</sdpi-select></sdpi-item>`,
		help: "Turn through the list of the user signed in on the player. Press to play it from where they left off. Tap the strip to switch between Continue Watching and Next Up. Hold the strip to play from the start.",
	},
	nowplaying: {
		title: "Now playing",
		fields: "",
		help: "Shows the poster of whatever's playing; press to play or pause. Leave this key's icon as the default, or Stream Deck won't let the artwork show.",
	},
	remote: {
		title: "Remote button",
		fields: `<sdpi-item label="Button"><sdpi-select setting="command" default="playpause">
				${REMOTE_BUTTONS.map(([v, l]) => `<option value="${v}">${l}</option>`).join("\n\t\t\t\t")}
			</sdpi-select></sdpi-item>`,
		help: "Pick which remote button this key is. Resume carries on if paused, or after Stop starts the top of Continue Watching from where you left off. The icon changes to match. Menu buttons (arrows, OK, Back, Home) need a player that accepts remote navigation, like the web player or an app on a TV.",
	},
};

const page = ({ title, fields, help }) => `<!doctype html>
<!-- Generated by scripts/build-ui.mjs: edit that, then run "npm run ui". -->
<html>
	<head lang="en">
		<title>${title}</title>
		<meta charset="utf-8" />
		<script src="https://sdpi-components.dev/releases/v4/sdpi-components.js"></script>
		<style>
			/* Plain text isn't styled by Elgato's components, so match the panel by hand. */
			.note, h4 { font-family: system-ui, "Segoe UI", sans-serif; color: #b8b8b8; margin: 10px 14px; }
			.note { font-size: 12px; line-height: 1.45; }
			h4 { font-size: 12px; font-weight: 600; margin-top: 18px; border-top: 1px solid #444; padding-top: 12px; }
			@media (prefers-color-scheme: light) { .note, h4 { color: #555555; } h4 { border-color: #ccc; } }
		</style>
	</head>
	<body>
		${fields}
		<sdpi-item label="Player">
			<sdpi-select setting="deviceId" datasource="getPlayers" hot-reload loading="Finding players…"></sdpi-select>
		</sdpi-item>
		<p class="note">${help}</p>

		<h4>Shared by every Jellyfin control</h4>
		<sdpi-item label="Server">
			<sdpi-textfield setting="serverUrl" global placeholder="http://192.168.1.20:8096" required></sdpi-textfield>
		</sdpi-item>
		<sdpi-item label="API key">
			<sdpi-password setting="apiKey" global placeholder="From Dashboard > API Keys" required></sdpi-password>
		</sdpi-item>
		<sdpi-item label="Default player">
			<sdpi-select setting="defaultDeviceId" global datasource="getDefaultPlayers" hot-reload loading="Finding players…"></sdpi-select>
		</sdpi-item>
		<sdpi-item label="Priority users">
			<sdpi-checkbox-list setting="users" global datasource="getUsers" hot-reload columns="1" loading="Finding users…"></sdpi-checkbox-list>
		</sdpi-item>
		<sdpi-item>
			<sdpi-checkbox setting="onlyUsers" global label="Ignore other users' players"></sdpi-checkbox>
		</sdpi-item>
		<sdpi-item>
			<sdpi-button onclick="document.querySelectorAll('sdpi-select[datasource], sdpi-checkbox-list').forEach((el) => el.refresh())">Refresh lists</sdpi-button>
		</sdpi-item>
		<p class="note">Each control uses its own Player if you pick one, otherwise the Default player.
			On Automatic, a priority user's player comes first (even paused), then whatever's playing.</p>
	</body>
</html>
`;

mkdirSync(OUT, { recursive: true });
for (const [name, def] of Object.entries(PAGES)) writeFileSync(`${OUT}/${name}.html`, page(def));
console.log(`wrote ${Object.keys(PAGES).length} settings pages to ${OUT}`);
